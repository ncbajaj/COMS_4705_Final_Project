"""Blinded human review of model vs. retrieval outputs on rare dev tuples.

Make a sheet from an evaluation run, have each teammate fill in a copy
independently, then unblind and score:

    python -m rarecrash.review make --predictions runs/dev-eval-pilot/predictions.jsonl --out runs/review
    python -m rarecrash.review score --key runs/review/key.csv --sheets runs/review/sheet_neil.csv runs/review/sheet_ziqi.csv --out runs/review/results.json

Each item shows one record's conditions with two outputs, A and B, in random
order. At most one record per condition tuple is sampled, because retrieval
returns the same narrative for every record in a tuple and repeats would
reveal which output is retrieval. The key file must not be opened until all
sheets are filled.
"""

import argparse
from collections import defaultdict
import csv
import json
from pathlib import Path
import random

from .pipeline import CONDITION_FIELDS, write_json


DETAIL_LABELS = ("coherent", "contradictory", "implausible")
DETAIL_ALIASES = {
    "coherent": "coherent", "c": "coherent",
    "contradictory": "contradictory", "ic": "contradictory",
    "implausible": "implausible", "imp": "implausible",
}
YES_VALUES = {"yes", "y", "1", "true"}
NO_VALUES = {"no", "n", "0", "false"}
JUDGMENTS = ("condition_contradiction", "details")
RUBRIC = """Blinded review: rare-condition crash narratives
==============================================

Each row gives the four requested conditions (surface, lighting, vehicles,
primary_cause) and two narratives, A and B. One is generated by the model and
one is a training narrative reused by the retrieval baseline. Do not try to
work out which is which, and do not open key.csv until every sheet is filled.

A narrative is expected to add details beyond the four conditions (weather,
road layout, traffic control, work zone, secondary cause, vehicle years and
headings). Extra details are NOT errors just
because the conditions do not mention them. Judge each narrative on two
separate questions, filling A_ columns for A and B_ columns for B.

1. condition_contradiction  (yes / no)
   Does the narrative contradict any of the four specified conditions?
   Answer yes only for a direct conflict with a condition; a condition that is
   simply not mentioned is not a contradiction.
   Example: conditions say "ice" and the narrative says the road was dry ->
   yes. Conditions say "Following Too Closely" and the narrative never names
   a cause -> no.
   Accepted: yes, y, 1, true / no, n, 0, false (any case).

2. details  (one label for all the extra, non-input details)
   coherent        The extra details fit together and could belong to a real
                   crash. Details the conditions do not confirm are fine.
                   Example: clear weather, a four-way intersection with a
                   traffic signal, and two vehicles heading north and east.
   contradictory   The extra details contradict each other or the narrative
                   itself. Example: it says one vehicle was involved and then
                   describes Vehicle 0 and Vehicle 1, or lists "Vehicle 0"
                   twice.
   implausible     The details are clearly implausible for a real crash.
                   Example: a work zone on a one-way road with a railroad
                   crossing gate and four vehicles all heading in different
                   directions, or a 1925 model car in a recent crash.
   Accepted: coherent or c; contradictory or ic; implausible or imp
   (any case). Use "contradictory" only for internal conflicts; a conflict
   with a condition goes under condition_contradiction. If both apply, pick
   the label that is most serious for the extra details.

preference    A, B, or tie: which narrative is the better description of a
              crash with these conditions overall.
notes         Optional. Note any contradiction, implausible detail, or
              truncation. Ignore missing spaces between sentences; the source
              data has them too.

Leave a cell blank rather than guessing if a narrative cannot be judged.
"""


def sample_items(predictions, count, seed, rare_only=True):
    """Pick records with both outputs, at most one per condition tuple."""
    by_id = defaultdict(dict)
    for row in predictions:
        by_id[row["id"]][row["system"]] = row
    candidates = [rows for rows in by_id.values()
                  if {"model", "retrieval"} <= rows.keys()
                  and all(r["output"] for r in rows.values())
                  and (rows["model"]["rare"] or not rare_only)]
    candidates.sort(key=lambda rows: rows["model"]["id"])
    rng = random.Random(seed)
    rng.shuffle(candidates)
    seen, items = set(), []
    for rows in candidates:
        key = tuple(rows["model"]["conditions"][f] for f in CONDITION_FIELDS)
        if key in seen:
            continue
        seen.add(key)
        systems = ["model", "retrieval"]
        rng.shuffle(systems)
        items.append({"item": len(items) + 1, "id": rows["model"]["id"],
                      "conditions": rows["model"]["conditions"],
                      "A": systems[0], "B": systems[1],
                      "output_A": rows[systems[0]]["output"],
                      "output_B": rows[systems[1]]["output"]})
        if len(items) == count:
            break
    return items


def sheet_fields():
    judgment_cols = [f"{side}_{j}" for side in "AB" for j in JUDGMENTS]
    return ["item", *CONDITION_FIELDS, "output_A", "output_B", *judgment_cols, "preference", "notes"]


def make(args):
    predictions = [json.loads(line) for line in open(args.predictions, encoding="utf-8")]
    items = sample_items(predictions, args.count, args.seed, rare_only=not args.include_common)
    if not items:
        raise ValueError("No records have both a model and a retrieval output")
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    fields = sheet_fields()
    for reviewer in args.reviewers:
        with (out / f"sheet_{reviewer}.csv").open("w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=fields)
            writer.writeheader()
            for it in items:
                writer.writerow({"item": it["item"], **it["conditions"],
                                 "output_A": it["output_A"], "output_B": it["output_B"]})
    with (out / "key.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["item", "id", "A", "B"])
        writer.writeheader()
        for it in items:
            writer.writerow({k: it[k] for k in ("item", "id", "A", "B")})
    (out / "instructions.txt").write_text(RUBRIC, encoding="utf-8")
    write_json(out / "review_info.json", {
        "predictions": str(args.predictions), "items": len(items), "requested": args.count,
        "seed": args.seed, "rare_only": not args.include_common, "reviewers": args.reviewers,
    })
    print(json.dumps({"items": len(items), "sheets": [f"sheet_{r}.csv" for r in args.reviewers],
                      "key": "key.csv (do not open until reviews are done)"}, indent=2))


def parse_yes_no(value):
    value = (value or "").strip().lower()
    if not value:
        return None
    if value in YES_VALUES:
        return True
    if value in NO_VALUES:
        return False
    raise ValueError(f"Condition contradiction must be yes or no: {value!r}")


def parse_details(value):
    value = (value or "").strip().lower()
    if not value:
        return None
    if value in DETAIL_ALIASES:
        return DETAIL_ALIASES[value]
    raise ValueError("Details must be coherent (c), contradictory (ic), "
                     f"or implausible (imp): {value!r}")


def parse_preference(value):
    value = (value or "").strip().lower()
    if not value:
        return None
    if value in {"a", "b"}:
        return value.upper()
    if value in {"tie", "t", "="}:
        return "tie"
    raise ValueError(f"Preference must be A, B, or tie: {value!r}")


def unblind(sheet_rows, key):
    """Convert one reviewer's A/B rows into per-system judgments by item."""
    judged = {}
    for row in sheet_rows:
        item = row["item"]
        side_to_system = {"A": key[item]["A"], "B": key[item]["B"]}
        pref = parse_preference(row.get("preference"))
        judged[item] = {
            "condition_contradiction": {
                side_to_system[s]: parse_yes_no(row.get(f"{s}_condition_contradiction"))
                for s in "AB"},
            "details": {side_to_system[s]: parse_details(row.get(f"{s}_details")) for s in "AB"},
            "preference": side_to_system.get(pref, pref),
        }
    return judged


def cohen_kappa(a, b):
    pairs = [(x, y) for x, y in zip(a, b) if x is not None and y is not None]
    if not pairs:
        return None
    labels = {x for pair in pairs for x in pair}
    n = len(pairs)
    observed = sum(x == y for x, y in pairs) / n
    expected = sum((sum(x == l for x, _ in pairs) / n) * (sum(y == l for _, y in pairs) / n)
                   for l in labels)
    return 1.0 if expected == 1 else (observed - expected) / (1 - expected)


def score(args):
    with open(args.key, newline="", encoding="utf-8") as f:
        key = {row["item"]: row for row in csv.DictReader(f)}
    reviewers = {}
    for path in args.sheets:
        with open(path, newline="", encoding="utf-8") as f:
            reviewers[Path(path).stem.removeprefix("sheet_")] = unblind(list(csv.DictReader(f)), key)

    systems = ("model", "retrieval")

    def share(count, n):
        return count / n if n else None

    def summarize(judged, system):
        cc = [j["condition_contradiction"][system] for j in judged.values()
              if j["condition_contradiction"][system] is not None]
        det = [j["details"][system] for j in judged.values() if j["details"][system] is not None]
        return {
            "condition_contradiction": {"n": len(cc), "yes": sum(cc),
                                        "share_yes": share(sum(cc), len(cc))},
            "details": {"n": len(det),
                        "counts": {l: det.count(l) for l in DETAIL_LABELS},
                        "shares": {l: share(det.count(l), len(det)) for l in DETAIL_LABELS}},
        }

    per_reviewer = {}
    for name, judged in reviewers.items():
        prefs = [j["preference"] for j in judged.values() if j["preference"]]
        per_reviewer[name] = {
            "systems": {system: summarize(judged, system) for system in systems},
            "preference": {p: sum(x == p for x in prefs) for p in ("model", "retrieval", "tie")},
            "items_with_preference": len(prefs),
        }
    agreement = None
    if len(reviewers) == 2:
        (n1, j1), (n2, j2) = reviewers.items()
        items = sorted(set(j1) & set(j2), key=int)

        def pooled(field):
            return ([j1[i][field][s] for i in items for s in systems],
                    [j2[i][field][s] for i in items for s in systems])

        agreement = {
            "reviewers": [n1, n2],
            "details_kappa": cohen_kappa(*pooled("details")),
            "condition_contradiction_kappa": cohen_kappa(*pooled("condition_contradiction")),
            "preference_kappa": cohen_kappa([j1[i]["preference"] for i in items],
                                            [j2[i]["preference"] for i in items]),
        }
    result = {"items": len(key), "per_reviewer": per_reviewer, "agreement": agreement}
    write_json(args.out, result)
    print(json.dumps(result, indent=2))


def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("make", help="build blinded sheets from an evaluation run")
    p.add_argument("--predictions", required=True, help="predictions.jsonl from rarecrash.evaluate")
    p.add_argument("--out", required=True)
    p.add_argument("--count", type=int, default=40)
    p.add_argument("--seed", type=int, default=4705)
    p.add_argument("--reviewers", nargs="+", default=["neil", "ziqi"])
    p.add_argument("--include-common", action="store_true",
                   help="sample from all dev records, not only rare tuples")
    p.set_defaults(func=make)
    p = sub.add_parser("score", help="unblind filled sheets and summarize")
    p.add_argument("--key", required=True)
    p.add_argument("--sheets", nargs="+", required=True)
    p.add_argument("--out", required=True)
    p.set_defaults(func=score)
    args = parser.parse_args()
    if args.command == "make" and args.count < 1:
        parser.error("count must be positive")
    args.func(args)


if __name__ == "__main__":
    main()
