"""Blinded human review of model vs. retrieval outputs on rare dev tuples.

Make a sheet from an evaluation run, have each teammate fill in a copy
independently, then unblind and score:

    python -m rarecrash.review make --predictions runs/dev-eval-pilot/predictions.jsonl --out runs/review
    python -m rarecrash.review score --key runs/review/key.csv --sheets runs/review/sheet_neil.csv runs/review/sheet_ziqi.csv --out runs/review/results.json

Each item shows one record's conditions with two outputs, A and B, in random
order. At most one record per condition tuple is sampled, because retrieval
returns the same narrative for every record in a tuple and repeats would
reveal which output is retrieval. The key file must not be opened until all
sheets are filled.
"""

import argparse
from collections import defaultdict
import csv
import json
from pathlib import Path
import random

from .pipeline import CONDITION_FIELDS, write_json


RATINGS = ("fluency", "consistency", "plausibility")
RUBRIC = """Blinded review: rare-condition crash narratives
==============================================

Each row gives the four requested conditions and two narratives, A and B.
One is generated by the model and one is a training narrative reused by the
retrieval baseline. Do not try to work out which is which, and do not open
key.csv until every sheet is filled.

Rate each narrative from 1 (poor) to 5 (excellent):

  fluency       Grammatical, readable text. Ignore missing spaces between
                sentences; the source data has them too.
  consistency   The narrative agrees with itself and with the conditions:
                e.g. the number of vehicles described matches the stated
                count, directions and actions make sense together, and the
                road, lighting and cause match the requested values.
  plausibility  Could this be a real Illinois crash report for these
                conditions?

preference    A, B, or tie: which narrative better describes a crash with
              these conditions overall.
notes         Optional. Note any factual error, contradiction, or truncation.

Leave a cell blank rather than guessing if a narrative cannot be judged.
"""


def sample_items(predictions, count, seed, rare_only=True):
    """Pick records with both outputs, at most one per condition tuple."""
    by_id = defaultdict(dict)
    for row in predictions:
        by_id[row["id"]][row["system"]] = row
    candidates = [rows for rows in by_id.values()
                  if {"model", "retrieval"} <= rows.keys()
                  and all(r["output"] for r in rows.values())
                  and (rows["model"]["rare"] or not rare_only)]
    candidates.sort(key=lambda rows: rows["model"]["id"])
    rng = random.Random(seed)
    rng.shuffle(candidates)
    seen, items = set(), []
    for rows in candidates:
        key = tuple(rows["model"]["conditions"][f] for f in CONDITION_FIELDS)
        if key in seen:
            continue
        seen.add(key)
        systems = ["model", "retrieval"]
        rng.shuffle(systems)
        items.append({"item": len(items) + 1, "id": rows["model"]["id"],
                      "conditions": rows["model"]["conditions"],
                      "A": systems[0], "B": systems[1],
                      "output_A": rows[systems[0]]["output"],
                      "output_B": rows[systems[1]]["output"]})
        if len(items) == count:
            break
    return items


def sheet_fields():
    rating_cols = [f"{side}_{r}" for side in "AB" for r in RATINGS]
    return ["item", *CONDITION_FIELDS, "output_A", "output_B", *rating_cols, "preference", "notes"]


def make(args):
    predictions = [json.loads(line) for line in open(args.predictions, encoding="utf-8")]
    items = sample_items(predictions, args.count, args.seed, rare_only=not args.include_common)
    if not items:
        raise ValueError("No records have both a model and a retrieval output")
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    fields = sheet_fields()
    for reviewer in args.reviewers:
        with (out / f"sheet_{reviewer}.csv").open("w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=fields)
            writer.writeheader()
            for it in items:
                writer.writerow({"item": it["item"], **it["conditions"],
                                 "output_A": it["output_A"], "output_B": it["output_B"]})
    with (out / "key.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["item", "id", "A", "B"])
        writer.writeheader()
        for it in items:
            writer.writerow({k: it[k] for k in ("item", "id", "A", "B")})
    (out / "instructions.txt").write_text(RUBRIC, encoding="utf-8")
    write_json(out / "review_info.json", {
        "predictions": str(args.predictions), "items": len(items), "requested": args.count,
        "seed": args.seed, "rare_only": not args.include_common, "reviewers": args.reviewers,
    })
    print(json.dumps({"items": len(items), "sheets": [f"sheet_{r}.csv" for r in args.reviewers],
                      "key": "key.csv (do not open until reviews are done)"}, indent=2))


def parse_rating(value):
    value = (value or "").strip()
    if not value:
        return None
    rating = int(float(value))
    if not 1 <= rating <= 5:
        raise ValueError(f"Rating out of range 1-5: {value!r}")
    return rating


def parse_preference(value):
    value = (value or "").strip().lower()
    if not value:
        return None
    if value in {"a", "b"}:
        return value.upper()
    if value in {"tie", "t", "="}:
        return "tie"
    raise ValueError(f"Preference must be A, B, or tie: {value!r}")


def unblind(sheet_rows, key):
    """Convert one reviewer's A/B rows into per-system judgments by item."""
    judged = {}
    for row in sheet_rows:
        item = row["item"]
        side_to_system = {"A": key[item]["A"], "B": key[item]["B"]}
        pref = parse_preference(row.get("preference"))
        judged[item] = {
            "ratings": {side_to_system[s]: {r: parse_rating(row.get(f"{s}_{r}")) for r in RATINGS}
                        for s in "AB"},
            "preference": side_to_system.get(pref, pref),
        }
    return judged


def cohen_kappa(a, b):
    pairs = [(x, y) for x, y in zip(a, b) if x is not None and y is not None]
    if not pairs:
        return None
    labels = {x for pair in pairs for x in pair}
    n = len(pairs)
    observed = sum(x == y for x, y in pairs) / n
    expected = sum((sum(x == l for x, _ in pairs) / n) * (sum(y == l for _, y in pairs) / n)
                   for l in labels)
    return 1.0 if expected == 1 else (observed - expected) / (1 - expected)


def score(args):
    with open(args.key, newline="", encoding="utf-8") as f:
        key = {row["item"]: row for row in csv.DictReader(f)}
    reviewers = {}
    for path in args.sheets:
        with open(path, newline="", encoding="utf-8") as f:
            reviewers[Path(path).stem.removeprefix("sheet_")] = unblind(list(csv.DictReader(f)), key)

    def mean(values):
        values = [v for v in values if v is not None]
        return {"mean": sum(values) / len(values) if values else None, "n": len(values)}

    per_reviewer = {}
    for name, judged in reviewers.items():
        prefs = [j["preference"] for j in judged.values() if j["preference"]]
        per_reviewer[name] = {
            "ratings": {system: {r: mean(j["ratings"][system][r] for j in judged.values())
                                 for r in RATINGS}
                        for system in ("model", "retrieval")},
            "preference": {p: sum(x == p for x in prefs) for p in ("model", "retrieval", "tie")},
            "items_with_preference": len(prefs),
        }
    agreement = None
    if len(reviewers) == 2:
        (n1, j1), (n2, j2) = reviewers.items()
        items = sorted(set(j1) & set(j2), key=int)
        agreement = {
            "reviewers": [n1, n2],
            "preference_kappa": cohen_kappa([j1[i]["preference"] for i in items],
                                            [j2[i]["preference"] for i in items]),
            "rating_exact_agreement": {
                r: mean(float(j1[i]["ratings"][s][r] == j2[i]["ratings"][s][r])
                        if j1[i]["ratings"][s][r] is not None and j2[i]["ratings"][s][r] is not None
                        else None
                        for i in items for s in ("model", "retrieval"))
                for r in RATINGS},
        }
    result = {"items": len(key), "per_reviewer": per_reviewer, "agreement": agreement}
    write_json(args.out, result)
    print(json.dumps(result, indent=2))


def main():
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("make", help="build blinded sheets from an evaluation run")
    p.add_argument("--predictions", required=True, help="predictions.jsonl from rarecrash.evaluate")
    p.add_argument("--out", required=True)
    p.add_argument("--count", type=int, default=40)
    p.add_argument("--seed", type=int, default=4705)
    p.add_argument("--reviewers", nargs="+", default=["neil", "ziqi"])
    p.add_argument("--include-common", action="store_true",
                   help="sample from all dev records, not only rare tuples")
    p.set_defaults(func=make)
    p = sub.add_parser("score", help="unblind filled sheets and summarize")
    p.add_argument("--key", required=True)
    p.add_argument("--sheets", nargs="+", required=True)
    p.add_argument("--out", required=True)
    p.set_defaults(func=score)
    args = parser.parse_args()
    if args.command == "make" and args.count < 1:
        parser.error("count must be positive")
    args.func(args)


if __name__ == "__main__":
    main()
